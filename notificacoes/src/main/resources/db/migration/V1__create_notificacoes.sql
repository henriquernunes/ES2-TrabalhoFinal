-- uma linha por idempotency_key (aluno + tarefa), datas em utc
CREATE TABLE notificacoes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(100)  NOT NULL,
    status          VARCHAR(10)   NOT NULL DEFAULT 'PENDENTE',
    tentativas      INTEGER       NOT NULL DEFAULT 0,
    ultimo_erro     VARCHAR(2000),
    user_email      VARCHAR(320)  NOT NULL,
    assign_name     VARCHAR(500)  NOT NULL,
    payload         VARCHAR(10000) NOT NULL,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em   TIMESTAMP WITH TIME ZONE NOT NULL,
    enviado_em      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_notificacoes_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_notificacoes_status CHECK (status IN ('PENDENTE', 'ENVIADO', 'FALHOU'))
);

CREATE INDEX idx_notificacoes_status ON notificacoes (status);
